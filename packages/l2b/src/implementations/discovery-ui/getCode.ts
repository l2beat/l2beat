export async function getCodeFromEtherscan(
  configReader: ConfigReader,
  project: string,
  address: ChainSpecificAddress,
  flatSourceClient: FlatSourceClient,
): Promise<ApiCodeResponse> {
  const entry = configReader
    .readDiscoveryWithReferences(project)
    .map((d) => d.entries.find((x) => x.address === address))
    .find((e) => e && e.type !== 'Reference')
  if (entry === undefined) {
    return { entryName: undefined, sources: [] }
  }

  const sources = await Promise.all(
    entrySourceLinks(entry).map(async ({ address, name }) => {
      const source =
        entry.type === 'Contract'
          ? await flatSourceClient.getContractFlat(address)
          : await flatSourceClient.getFlat(address)
      return {
        name,
        code:
          source.kind === 'flat' ? addFlattenerNote(source.flat) : source.flat,
      }
    }),
  )
  return { entryName: entry.name, sources }
}

// The sources the code panel lists for an entry, in the order it lists them.
export function entrySourceLinks(
  entry: EntryParameters,
): { address: ChainSpecificAddress; name: string }[] {
  const addresses = [entry.address, ...get$Implementations(entry.values)]
  const names = entry.implementationNames ?? {}
  return addresses.map((a, i) => ({
    address: a,
    name: names[a] ?? getFallbackSourceName(i, addresses.length),
  }))
}

function getFallbackSourceName(index: number, total: number): string {
  if (index === 0 && total > 1) return 'Proxy'
  if (total <= 2) return 'Implementation'
  return `Implementation #${index}`
}

export function getCodeFromDisk(
  configReader: ConfigReader,
  project: string,
  address: ChainSpecificAddress,
): ApiCodeResponse {
  const { entryName, codePaths } = getCodePaths(configReader, project, address)

  if (!isFlatCodeCurrent(configReader, project, address, codePaths)) {
    throw new Error('Flat code is outdated')
  }

  return {
    entryName,
    sources: codePaths
      .map(({ name, path }) => ({
        name: name,
        code: addFlattenerNote(readFileSync(path, 'utf-8')),
      }))
      .sort((a, b) => compareFiles(a.name, b.name)),
  }
}

export function getAllCode(
  configReader: ConfigReader,
  project: string,
): Record<string, ApiCodeResponse> {
  const result: Record<string, ApiCodeResponse> = {}
  const discoveries = configReader.readDiscoveryWithReferences(project)

  // Get all unique addresses across all chains
  const allAddresses = discoveries.flatMap((discovery) =>
    discovery.entries
      .filter((e) => e.type === 'Contract')
      .map((entry) => entry.address),
  )

  for (const fullAddress of allAddresses) {
    try {
      const { entryName, codePaths } = getCodePaths(
        configReader,
        project,
        fullAddress,
      )

      const availableCodePaths = codePaths.filter(({ path }) =>
        existsSync(path),
      )

      result[fullAddress] = {
        entryName,
        sources: availableCodePaths
          .map(({ name: fileName, path }) => ({
            name: fileName,
            code: addFlattenerNote(readFileSync(path, 'utf-8')),
          }))
          .sort((a, b) => compareFiles(a.name, b.name)),
      }
    } catch (error) {
      console.error(`Failed to get code for address ${fullAddress}`, error)
    }
  }

  return result
}
